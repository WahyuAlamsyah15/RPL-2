    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
                                             
        String username = jTextUsername.getText();
        String password = jTextPassword.getText(); 

        String DB_URL = "jdbc:mysql://localhost:3306/act3";
        String DB_USER = "root";
        String DB_PASS = "";

        if (username.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Username dan Password kosong!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String sql = "SELECT * FROM user WHERE username = ? AND password = ?";

        try (java.sql.Connection conn = java.sql.DriverManager.getConnection(DB_URL, DB_USER, DB_PASS);
             java.sql.PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, username);
            ps.setString(2, password);

            try (java.sql.ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Login Berhasil!", "Sukses", javax.swing.JOptionPane.INFORMATION_MESSAGE);

                    // --- PROSES PERPINDAHAN PANEL DI JENDELA YANG SAMA ---
                    java.awt.Window window = javax.swing.SwingUtilities.getWindowAncestor(this);
                    if (window instanceof javax.swing.JFrame) {
                        javax.swing.JFrame mainFrame = (javax.swing.JFrame) window;

                        // Ganti isi jendela dengan AdminPanel
                        AdminPanel admin = new AdminPanel();
                        mainFrame.getContentPane().removeAll();
                        mainFrame.getContentPane().add(admin);

                        // Sesuaikan ulang ukuran jendela jika ukuran AdminPanel berbeda dengan LoginPanel
                        mainFrame.pack(); 
                        mainFrame.setLocationRelativeTo(null); // Tetap di tengah layar

                        // Refresh layar
                        mainFrame.revalidate();
                        mainFrame.repaint();
                    }
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Username atau Password salah!", "Gagal", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error Database:\n" + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }


    }//GEN-LAST:event_jButton1ActionPerformed


