    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
                                             
        String username = jTextUsername.getText();
        String password = jTextPassword.getText(); 

        if (username.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Username dan Password kosong!",
                    "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            boolean loginBerhasil = userService.authenticate(username, password).isPresent();

                if (loginBerhasil) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Login Berhasil!", 
                            "Sukses", javax.swing.JOptionPane.INFORMATION_MESSAGE);
          
                    java.awt.Window window = javax.swing.SwingUtilities.getWindowAncestor(this);
                    if (window instanceof javax.swing.JFrame) {
                        javax.swing.JFrame mainFrame = (javax.swing.JFrame) window;
                        AdminPanel admin = new AdminPanel();
                        mainFrame.getContentPane().removeAll();
                        mainFrame.getContentPane().add(admin);
                        mainFrame.pack(); 
                        mainFrame.setLocationRelativeTo(null); 
                        mainFrame.revalidate();
                        mainFrame.repaint();
                    }
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Username atau Password salah!",
                            "Gagal", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
        } catch (RuntimeException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error Database:\n" + e.getMessage(), 
                    "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }


    }//GEN-LAST:event_jButton1ActionPerformed

